@app.cell(column=2)
def chat_panel():
    """AI chat assistant with FTS5 retrieval — column 2."""
    from pydantic_ai.messages import ModelRequest, UserPromptPart, ModelResponse, TextPart

    last_response, set_last_response = mo.state("")

    async def respond(messages, config):
        history = []
        for msg in messages[:-1]:
            if msg.role == "user":
                history.append(ModelRequest(parts=[UserPromptPart(content=msg.content)]))
            elif msg.role == "assistant":
                history.append(ModelResponse(parts=[TextPart(content=msg.content)]))

        full_text = ""
        async with wiki_agent.run_stream(
            messages[-1].content, deps=wiki_db_path, message_history=history
        ) as result:
            async for chunk in result.stream_text(delta=True):
                full_text += chunk
                yield chunk

        set_last_response(full_text)

    chat = mo.ui.chat(
        respond,
        prompts=wiki_chat_config.suggested_prompts,
        max_height=600,
    )
    mo.vstack([mo.md("### Chat with your Wiki"), chat], gap=2)
    return (last_response,)


@app.cell
def save_form(last_response):
    """Save-to-wiki form — value persists after submission (unlike a button)."""
    _title = mo.ui.text(label="Title", placeholder="Page title...")
    _category = mo.ui.dropdown(
        {"Concept": "concept", "Summary": "summary"},
        label="Category",
        value="Concept",
    )

    def _validate(v):
        if not last_response():
            return "Chat with the assistant first."
        if not (v.get("title") or "").strip():
            return "Title cannot be empty."
        return None

    form = (
        mo.md("### Save last response to wiki\n\n{title}\n\n{category}")
        .batch(title=_title, category=_category)
        .form(submit_button_label="💾 Save to wiki", validate=_validate)
    )
    form
    return (form,)


@app.cell
def save_action(form, last_response):
    """Show result after form submission — re-runs when form.value changes."""
    from openai import OpenAI
    from domain.chat.wiki_tools import save_to_wiki

    _llm_client = OpenAI(base_url=settings.LLM_BASE_URL, api_key=settings.LLM_API_KEY)

    def _run():
        if form.value is None:
            return mo.md("")
        title = (form.value.get("title") or "").strip()
        category = form.value.get("category", "concept")
        try:
            msg = save_to_wiki(
                wiki_db_path, WIKI_PATH, title, last_response(), category,
                client=_llm_client, model=settings.LLM_MODEL,
            )
            return mo.callout(mo.md(f"✅ {msg}"), kind="success")
        except Exception as exc:
            return mo.callout(mo.md(f"❌ Save failed: {exc}"), kind="danger")

    out = _run()
    out
    return



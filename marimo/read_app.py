@app.cell
def wiki_helpers():
    """File helpers: scan and read wiki pages."""
    wiki_dir = WIKI_PATH / "wiki"
    wiki_dir.mkdir(parents=True, exist_ok=True)

    def scan_pages():
        return sorted(
            str(p.relative_to(wiki_dir).with_suffix(""))
            for p in wiki_dir.rglob("*.md")
        )

    def read_page(rel_path):
        path = wiki_dir / f"{rel_path}.md"
        return path.read_text(encoding="utf-8") if path.exists() else ""

    return read_page, scan_pages


@app.cell
def page_state(scan_pages):
    """Reactive state: page list and current selection."""
    page_list, set_page_list = mo.state(scan_pages(), allow_self_loops=True)
    initial_pages = page_list()
    selected_page, set_selected_page = mo.state(
        initial_pages[0] if initial_pages else None
    )
    delete_trigger, set_delete_trigger = mo.state(None)
    last_delete_event, set_last_delete_event = mo.state(0)
    return (
        delete_trigger,
        last_delete_event,
        page_list,
        selected_page,
        set_delete_trigger,
        set_last_delete_event,
        set_page_list,
        set_selected_page,
    )


@app.cell
def left_panel(page_list, scan_pages, set_page_list, set_selected_page):
    """Navigation sidebar — column 0."""
    pages = page_list()

    def _page_row(p):
        parts = p.rsplit("/", 1)
        directory = parts[0] if len(parts) > 1 else ""
        slug = parts[-1]
        title = slug.replace("-", " ").replace("_", " ").title()
        return {"Title": title, "Directory": directory, "Slug": slug}

    _table_data = [_page_row(p) for p in pages] if pages else [{"Title": "(no pages)", "Directory": "", "Slug": ""}]

    def _on_select(rows):
        if not rows:
            return
        r = rows[0]
        path = f"{r['Directory']}/{r['Slug']}" if r["Directory"] else r["Slug"]
        set_selected_page(path)

    page_selector = mo.ui.table(
        _table_data,
        selection="single",
        on_change=_on_select,
    )
    refresh_btn = mo.ui.button(
        label="⟳ Refresh",
        on_click=lambda _: set_page_list(scan_pages()),
    )
    mo.vstack([page_selector, refresh_btn], gap=2)
    return



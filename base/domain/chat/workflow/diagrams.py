"""The flowchart of each chat workflow, generated from the graphs.

`WORKFLOWS` names the four workflows, in the order of a turn, with one sentence
that says what each workflow does. `markdown()` writes one section per workflow,
with its Mermaid flowchart in English (`flowchart.flowchart`, the conversion that
the audit page uses), without the marks of a turn.

`scripts/workflow_diagrams.py` writes `markdown()` to `docs/workflow_diagrams.md`,
and `tests/unit/test_workflow_diagrams_doc.py` fails when the file differs.
"""

from __future__ import annotations

import textwrap

from domain.chat.workflow import input_checks, output_checks
from domain.chat.workflow.flowchart import flowchart

# (title of the section, graph, what the workflow does), in the order of a turn.
WORKFLOWS = (
    ("Pre-retrieval, input", input_checks.graph,
     "The input workflow of the pre-retrieval mode builds the history, checks the question, "
     "retrieves the text that the prompt injects and ends in a refusal or in a call to the model."),
    ("Pre-retrieval, output", output_checks.graph,
     "The output workflow of the pre-retrieval mode checks the answer of the model, adds the table, "
     "the citations and the warning, and ends in the answer or in a refusal."),
    ("Strict, input", input_checks.strict_graph,
     "The input workflow of the strict mode builds the history and the question that the model "
     "receives, and checks nothing in the question."),
    ("Strict, output", output_checks.strict_graph,
     "The output workflow of the strict mode checks that a tool returned evidence, adds the table "
     "and the citation, and shows the answer."),
)

_HEADER = """\
# Workflow diagrams

This file is generated by `scripts/workflow_diagrams.py` from the graphs of the
chat workflows (`base/domain/chat/workflow/diagrams.py`). Do not edit it by
hand: the test `tests/unit/test_workflow_diagrams_doc.py` fails when the file
differs from the graphs. Regenerate it with:

    uv run python scripts/workflow_diagrams.py

Each diagram is the one that the audit page of a conversation draws, in English
and without the marks of a turn. A box is a step, with its identifier and its
short text. A diamond is a decision, with its question. An arrow that leaves a
decision carries the label of its branch. The small filled circle is the start
of the workflow, and the framed circle is its end.

What each node does is in [`query_nodes.md`](query_nodes.md). The calls to the
model run between the two workflows of a mode, outside both. The streaming mode
has no workflows.
"""


def markdown() -> str:
    """The text of `docs/workflow_diagrams.md`."""
    sections = [
        f"## {title}\n\n{textwrap.fill(sentence, 79)}\n\n```mermaid\n{flowchart(graph.render())}\n```\n"
        for title, graph, sentence in WORKFLOWS
    ]
    return "\n".join([_HEADER, *sections])
